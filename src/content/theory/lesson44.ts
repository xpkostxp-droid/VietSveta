import type { TheoryBlock } from '../../types';
import { lesson44Vocabulary } from '../vocabulary/lesson44';

function vocabulary(heading: string, numbers: number[], note?: string): TheoryBlock {
  return {
    kind: 'vocab', heading, note,
    items: numbers.map(number => {
      const item = lesson44Vocabulary.find(word => word.id === `l44-${String(number).padStart(2, '0')}`);
      if (!item) throw new Error(`Missing lesson 44 word: ${number}`);
      return item;
    }),
  };
}

